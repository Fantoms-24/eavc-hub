def build_shift_summary_prompt(
    *,
    position_name: str,
    session_meta: dict,
    items_text: str,
    narrative: bool = False,
) -> str:
    if narrative:
        format_block = """
Формат ответа (главная задача — описать, что происходило в смене):
1. **Что происходило в смене** — 3-6 коротких пунктов по сути перехватов: задачи, перемещения, связь, обстрелы, запросы, координация. Опирайся только на текст бланков.
2. **По каналам** — для каждого подразделения/частоты/группы с содержательными перехватами одна строка:
   Подразделение — частота / группа — кратко что было (1-2 предложения по смыслу эфира).
3. **Критические события** — только если в данных есть 300-е/раненые, 200-е/убитые, бой, эвакуация или срочные запросы. Иначе одной строкой: "Критических событий не обнаружено".
4. **МПС и обеспечение** — только подтверждённые жалобы/паника/снабжение/связь; если нет — "МПС-признаки не обнаружены".
5. **Что уточнить оператору** — 2-3 вопроса по пробелам в данных.

Не начинай ответ с перечисления кодов 200/300/МПС, если пользователь просит общую сводку смены.
Сначала дай понятное описание событий смены, затем риски и уточнения.
""".strip()
    else:
        format_block = """
Формат ответа:
1. Итог смены: 2-4 коротких пункта — что происходило по перехватам.
2. Приоритет: санитарные потери / критические события.
   Если есть 300-е/раненые или 200-е/убитые, этот блок подробно раскрывает подразделение, частоту, группу и суть.
   Если потерь нет, напиши "Санитарные потери не обнаружены".
3. Остальные каналы коротко: по одной строке на канал.
   Формат: Подразделение — частота / группа — коротко что было.
4. Морально-психологическая оценка: только подтвержденные жалобы/паника/усталость/отказ/снабжение или "не обнаружено".
5. Что уточнить оператору: 2-4 самых важных вопроса.
""".strip()

    return f"""
Сделай краткую аналитическую сводку смены по перехватам.

Позиция: {position_name or "не указана"}
Смена: id={session_meta.get("id")}, начало={session_meta.get("started_at")}, конец={session_meta.get("ended_at") or "активна"}

Важный словарь для анализа:
- "300", "300-й", "трехсотый", "трёхсотый" обычно означает раненый.
- "200", "200-й", "двухсотый" обычно означает убитый/погибший.
- "ранен", "раненный", "раненый", "потери", "эвакуация", "медик" относятся к возможным санитарным потерям.
- Учитывай эти термины только если они есть в данных перехватов. Не выдумывай потери.

Морально-психологическая проверка:
- Ищи жалобы военнослужащих на командование, снабжение, отсутствие связи, нехватку БК, еды, воды, топлива, медицины.
- Ищи признаки паники, страха, усталости, деморализации, отказа выполнять задачу, просьбы об отходе или эвакуации.
- Ищи конфликты между подразделениями, обвинения, недовольство потерями, просьбы о помощи.
- Если таких признаков нет, прямо напиши: "МПС-признаки жалоб/паники не обнаружены".
- Не делай психологических выводов без текстового подтверждения.

Позывные:
- В данных могут быть коды вида "(12115 — Джон)" или список "Позывные в бланке".
- Когда пересказываешь, кто говорил в эфире, указывай понятное имя: "Джон (12115)", а не только числовой код.
- Если имени позывного нет в справочнике, оставляй код как есть.

{format_block}

Если подразделение пустое или не указано в данных, напиши "не указано".
Если по одной частоте/группе несколько записей, объедини их в одну строку и кратко суммируй содержание.
Если есть жалобы или признаки морально-психологического напряжения, укажи подразделение, частоту, группу и короткий фрагмент смысла.
Не делай одинаково подробную сводку по всем каналам, если критическое событие есть только в одном подразделении.

Данные перехватов:
{items_text}
""".strip()


def build_period_report_prompt(*, position_name: str, start_ts: str, end_ts: str, items_text: str) -> str:
    return f"""
Сделай полноценный аналитический отчет по перехватам за период. Это может быть длинный период, например месяц.
Главная цель: показать, что происходило по подразделениям, где были потери, бои, эвакуации, жалобы и проблемы обеспечения.

Позиция: {position_name or "все доступные"}
Период: {start_ts} — {end_ts}

Важный словарь для анализа:
- "300", "300-й", "трехсотый", "трёхсотый" обычно означает раненый.
- "200", "200-й", "двухсотый" обычно означает убитый/погибший.
- "ранен", "раненный", "раненый", "потери", "эвакуация", "медик" относятся к возможным санитарным потерям.
- Учитывай эти термины только если они есть в данных перехватов. Не выдумывай потери.

Морально-психологическая проверка:
- Ищи жалобы военнослужащих на командование, снабжение, отсутствие связи, нехватку БК, еды, воды, топлива, медицины.
- Ищи признаки паники, страха, усталости, деморализации, отказа выполнять задачу, просьбы об отходе или эвакуации.
- Ищи конфликты между подразделениями, обвинения, недовольство потерями, просьбы о помощи.
- Если таких признаков нет, прямо напиши: "МПС-признаки жалоб/паники не обнаружены".
- Не делай психологических выводов без текстового подтверждения.

Позывные:
- В данных могут быть коды вида "(12115 — Джон)" или список "Позывные в бланке".
- Когда пересказываешь, кто говорил в эфире, указывай понятное имя: "Джон (12115)", а не только числовой код.
- Если имени позывного нет в справочнике, оставляй код как есть.

Формат ответа:
1. Итог периода: 5-8 самых важных выводов.
2. Приоритетные события периода:
   - Санитарные потери / 300-е: сколько найдено признаков, по каким подразделениям, когда, где.
   - 200-е / убитые: сколько найдено признаков, по каким подразделениям, когда, где.
   - Бои / обстрелы / эвакуации: где и когда были признаки активных событий.
   Если признаков нет, прямо напиши "не обнаружено".
3. Отчет по подразделениям.
   Для каждого подразделения, где есть содержательные перехваты, дай отдельный блок:
   - Подразделение: ...
   - Активность: частоты/группы и кратко что происходило.
   - Потери: 300-е/200-е с датами и количеством найденных признаков; если нет, "не обнаружено".
   - Бои/эвакуации: что было и когда; если нет, "не обнаружено".
   - Морально-психологические признаки: жалобы, паника, усталость, отказ, обеспечение, связь, БК, вода, медицина; если нет, "не обнаружено".
   - Что уточнить: 1-3 вопроса аналитику.
4. Общие закономерности: повторяющиеся события, проблемные подразделения, частоты/группы с наибольшим риском.
5. Рекомендации аналитику: что проверить дальше.

Не делай выводов без опоры на текст. Если данных мало, так и напиши.
Если подразделение пустое или не указано в данных, напиши "не указано".
Если ниже есть блок "Предварительная автоматическая карта событий периода", обязательно используй его как опорный список найденных признаков.
Считай только найденные признаки/упоминания, а не фактические подтвержденные потери. Формулируй: "найдено признаков/упоминаний", если точное число людей не подтверждено.
Если в тексте есть явное количество ("двое 300-х"), укажи это отдельно как текстовое указание.
Если есть жалобы или признаки морально-психологического напряжения, укажи подразделение, дату/смену, частоту, группу и короткий фрагмент смысла.
Не смешивай подразделения, частоты и группы в один список.

Данные перехватов:
{items_text}
""".strip()


def build_intercept_proofread_prompt(*, text: str) -> str:
    return f"""
Проверь текст бланка радиоперехвата на очевидные опечатки и ошибки распознавания.

Правила:
- Исправляй только очевидные ошибки по смыслу: например "асколок" -> "осколок".
- Не меняй время, переносы строк, структуру строк, частоты, группы, числовые коды и позывные в скобках.
- Не меняй армейский сленг, сокращения и жаргон, если это может быть намеренная запись оператора.
- Не перефразируй и не улучшай стиль. Только точечные исправления слов.
- Если не уверен, не исправляй.

Верни строго JSON без markdown:
{{
  "corrected_text": "полный исправленный текст",
  "issues": [
    {{
      "original": "ошибочное слово или фраза",
      "corrected": "исправленный вариант",
      "reason": "короткое объяснение"
    }}
  ]
}}

Текст бланка:
{text}
""".strip()


def build_reduce_prompt(*, task_title: str, partial_summaries: str) -> str:
    return f"""
Ниже несколько промежуточных AI-сводок по частям одного набора перехватов.
Собери единый итоговый отчет без повторов.

Задача: {task_title}

Если задача относится к анализу периода, сохрани структуру:
1. Итог периода.
2. Приоритетные события периода.
3. Отчет по подразделениям.
4. Общие закономерности.
5. Рекомендации аналитику.
Не теряй даты, подразделения, частоты/группы, признаки 300/200, бои/эвакуации и МПС/обеспечение из промежуточных сводок.

Промежуточные сводки:
{partial_summaries}
""".strip()
